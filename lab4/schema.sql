DROP TABLE IF EXISTS
    promotion_product, promotion_android, shop_product,
    order_topic, order_product, order_android,
    orders, pairing, topic_phrase,
    alcohol, snack, product,
    promotion, call_book, admin, topic, technician, shop, client, android
CASCADE;

-- E1 андроид
CREATE TABLE android (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    passport TEXT NOT NULL UNIQUE,
    sex TEXT NOT NULL CHECK (sex IN ('М', 'Ж')),
    class TEXT NOT NULL,
    litrage NUMERIC(5,2) NOT NULL CHECK (litrage > 0),
    operating_cost NUMERIC(8,2) NOT NULL CHECK (operating_cost > 0),
    call_price NUMERIC(8,2) NOT NULL CHECK (call_price > 0)
);

--E2 клиент
CREATE TABLE client (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name TEXT NOT NULL UNIQUE, -- AK1.1
    birth_date DATE NOT NULL
        CHECK (birth_date <= CURRENT_DATE - INTERVAL '18 years'),
    address TEXT NOT NULL,
    alco_experience SMALLINT NOT NULL DEFAULT 0 CHECK (alco_experience >= 0),
    access_rights TEXT NOT NULL DEFAULT 'client'
);

-- E5 магазин
CREATE TABLE shop (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL UNIQUE,
    address TEXT NOT NULL UNIQUE,
    is_priority BOOLEAN NOT NULL DEFAULT FALSE,
    open_time TIME NOT NULL,
    close_time TIME NOT NULL
);

-- E6 техник
CREATE TABLE technician (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name TEXT NOT NULL,
    passport TEXT NOT NULL UNIQUE,
    salary NUMERIC(8,2) NOT NULL CHECK (salary >= 27093),
    served_androids_month INT NOT NULL DEFAULT 0 CHECK (served_androids_month >= 0),
    access_rights TEXT NOT NULL DEFAULT 'technician',
    bonus NUMERIC(8,2) NOT NULL DEFAULT 0 CHECK (bonus >= 0)
);

--E7 тема беседы
CREATE TABLE topic (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL UNIQUE
);

-- E20 Реплики
CREATE TABLE topic_phrase (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    topic_id INT NOT NULL
        REFERENCES topic (id) ON DELETE CASCADE ON UPDATE CASCADE,
    android_reply TEXT NOT NULL
);

-- E8 учётная книга вызовов
CREATE TABLE call_book (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    period_start DATE NOT NULL UNIQUE,
    period_end DATE NOT NULL,
    CHECK (period_end > period_start)
);

--E10 администратор
CREATE TABLE admin (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name TEXT NOT NULL,
    passport TEXT NOT NULL UNIQUE,
    salary NUMERIC(8,2) NOT NULL CHECK (salary > 0),
    access_rights TEXT NOT NULL DEFAULT 'admin'
);

--E11. акция
CREATE TABLE promotion (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL UNIQUE,
    price NUMERIC(8,2) NOT NULL CHECK (price >= 0),
    condition TEXT,
    start_date DATE NOT NULL,
    end_date DATE NOT NULL,
    CHECK (end_date >= start_date)
);

--E17 товар
CREATE TABLE product (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kind TEXT NOT NULL CHECK (kind IN ('alcohol', 'snack'))
);

-- E3 алкоголь
CREATE TABLE alcohol (
    product_id INT PRIMARY KEY
        REFERENCES product (id) ON DELETE CASCADE ON UPDATE CASCADE,
    name TEXT NOT NULL,
    brand TEXT NOT NULL,
    type TEXT NOT NULL,
    volume_l NUMERIC(5,2) NOT NULL CHECK (volume_l >= 0),
    quality TEXT NOT NULL,
    density NUMERIC(4,3) NOT NULL CHECK (density > 0),
    strength NUMERIC(4,1) NOT NULL CHECK (strength BETWEEN 0 AND 100),
    UNIQUE (name, brand, type)
);

-- E4 закуска
CREATE TABLE snack (
    product_id INT PRIMARY KEY
        REFERENCES product (id) ON DELETE CASCADE ON UPDATE CASCADE,
    name TEXT NOT NULL UNIQUE,
    type TEXT NOT NULL,
    weight_g INT NOT NULL CHECK (weight_g >= 0)
);

-- E9 Сочетание алкоголя и закусок
CREATE TABLE pairing (
    alcohol_id INT NOT NULL
        REFERENCES alcohol (product_id) ON DELETE CASCADE ON UPDATE CASCADE,
    snack_id INT NOT NULL
        REFERENCES snack (product_id) ON DELETE CASCADE ON UPDATE CASCADE,
    topic_id INT NOT NULL
        REFERENCES topic (id) ON DELETE CASCADE ON UPDATE CASCADE,
    alco_experience SMALLINT NOT NULL CHECK (alco_experience >= 0),
    PRIMARY KEY (alcohol_id, snack_id, topic_id)
);

-- E14 заказ
CREATE TABLE orders (
    id INT GENERATED BY DEFAULT AS IDENTITY,
    book_id INT NOT NULL
        REFERENCES call_book (id) ON DELETE RESTRICT ON UPDATE CASCADE,
    client_id INT NOT NULL
        REFERENCES client (id) ON DELETE RESTRICT ON UPDATE CASCADE,
    shop_id INT
        REFERENCES shop (id) ON DELETE SET NULL ON UPDATE CASCADE,
    technician_id INT NOT NULL
        REFERENCES technician (id) ON DELETE RESTRICT ON UPDATE CASCADE,
    promotion_id INT
        REFERENCES promotion (id) ON DELETE SET NULL ON UPDATE CASCADE,
    started_at TIMESTAMP NOT NULL,
    hours SMALLINT NOT NULL CHECK (hours >= 1),
    android_name TEXT NOT NULL,
    extra_service BOOLEAN NOT NULL DEFAULT FALSE,
    is_paid BOOLEAN NOT NULL DEFAULT FALSE,
    is_completed BOOLEAN NOT NULL DEFAULT FALSE,
    PRIMARY KEY (id, book_id),
    UNIQUE (id),
    CHECK (shop_id IS NULL OR extra_service)
);

-- E12 андроид в заказе
CREATE TABLE order_android (
    order_id INT NOT NULL
        REFERENCES orders (id) ON DELETE CASCADE ON UPDATE CASCADE,
    android_id INT NOT NULL
        REFERENCES android (id) ON DELETE RESTRICT ON UPDATE CASCADE,
    PRIMARY KEY (order_id, android_id)
);

--E13 товар в заказе
CREATE TABLE order_product (
    order_id INT NOT NULL
        REFERENCES orders (id) ON DELETE CASCADE ON UPDATE CASCADE,
    product_id INT NOT NULL
        REFERENCES product (id) ON DELETE RESTRICT ON UPDATE CASCADE,
    quantity INT NOT NULL CHECK (quantity > 0),
    PRIMARY KEY (order_id, product_id)
);

--E15 тема в заказе
CREATE TABLE order_topic (
    order_id INT NOT NULL
        REFERENCES orders (id) ON DELETE CASCADE ON UPDATE CASCADE,
    topic_id INT NOT NULL
        REFERENCES topic (id) ON DELETE RESTRICT ON UPDATE CASCADE,
    PRIMARY KEY (order_id, topic_id)
);

-- E16 товар в магазине
CREATE TABLE shop_product (
    shop_id INT NOT NULL
        REFERENCES shop (id) ON DELETE CASCADE ON UPDATE CASCADE,
    product_id INT NOT NULL
        REFERENCES product (id) ON DELETE CASCADE ON UPDATE CASCADE,
    price NUMERIC(8,2) NOT NULL CHECK (price > 0),
    stock INT NOT NULL DEFAULT 0 CHECK (stock >= 0),
    PRIMARY KEY (shop_id, product_id)
);

-- E18 андроид в акции
CREATE TABLE promotion_android (
    promotion_id INT NOT NULL
        REFERENCES promotion (id) ON DELETE CASCADE ON UPDATE CASCADE,
    android_id INT NOT NULL
        REFERENCES android (id) ON DELETE CASCADE ON UPDATE CASCADE,
    PRIMARY KEY (promotion_id, android_id)
);

-- E19 товар в акции
CREATE TABLE promotion_product (
    promotion_id INT NOT NULL
        REFERENCES promotion (id) ON DELETE CASCADE ON UPDATE CASCADE,
    product_id INT NOT NULL
        REFERENCES product (id) ON DELETE CASCADE ON UPDATE CASCADE,
    PRIMARY KEY (promotion_id, product_id)
);
